// Общая рассыльная событий для долгоживущих объектов: сокет, WebRTC-сеть,
// голос, рой, управление, настройки.
//
// Пара `emit`/`on` была скопирована слово в слово в четырёх классах, настройки
// звали её иначе — `on(fn)`, без имени события, — а сокет не имел её вовсе, и
// слушать его приходилось вручную: `addEventListener` плюс разбор `detail` в
// каждом обработчике. Один и тот же по смыслу вызов выглядел в проекте тремя
// разными способами, и выбор между ними каждый раз приходилось вспоминать.
//
// EventTarget под этим оставлен намеренно: он есть в каждом движке, умеет
// снимать подписки и не тянет за собой ни строчки чужого кода.

export class Emitter extends EventTarget {
  /**
   * Разослать событие. Тело всегда объект — тогда у обработчика один и тот же
   * разбор, а добавить в сообщение поле можно, не переписывая подписчиков.
   */
  emit(type, detail = {}) {
    this.dispatchEvent(new CustomEvent(type, { detail }));
  }

  /**
   * Подписаться. Обработчик получает сразу тело события, а не обёртку вокруг
   * него: `detail` — подробность реализации, и в прикладном коде ей не место.
   *
   * Возвращает функцию отписки: подписчик редко переживает того, на кого
   * подписан, но когда переживает — снять подписку больше нечем.
   */
  on(type, fn) {
    const wrap = (e) => fn(e.detail);
    this.addEventListener(type, wrap);
    return () => this.removeEventListener(type, wrap);
  }
}
