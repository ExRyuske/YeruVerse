// Перерисовка по имени.
//
// Список участников зависит от трансляций, трансляции — от того, кто вошёл, а
// замок возле ника — сразу от всего. Пока модули звали функции отрисовки друг
// друга напрямую, они и импортировали друг друга по кругу: список участников
// знал про сцену, сцена — про список.
//
// Здесь этот узел развязан. Модуль объявляет, что умеет рисовать, а остальные
// просят перерисовать по имени, ничего про исполнителя не зная. Незанятое имя
// молча ничего не делает — это нормально: в комнате есть не все поверхности
// сразу.

const painters = new Map();

/** Объявить, кто рисует эту поверхность. */
export function painter(name, fn) {
  painters.set(name, fn);
}

/** Перерисовать перечисленное — в том порядке, в каком названо. */
export function render(...names) {
  for (const name of names) painters.get(name)?.();
}
