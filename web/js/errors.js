// Причина отказа человеческой строкой — одна на всё приложение.
//
// Наверх прилетает то `Error`, то голая строка, то отказ нативного моста, и по
// проекту это разбиралось восемью одинаковыми `e.message ?? e`. Каждый раз с
// шансом показать человеку `[object Object]` вместо причины — а показывается
// это ровно там, где что-то уже сломалось и объяснение нужнее всего.
//
// Модуль ничего не импортирует намеренно: разбирать отказ приходится и в
// интерфейсе, и в слоях под ним — в мосту к оболочке, в удалённом управлении, —
// а те про интерфейс не знают и знать не должны.

export function reason(e) {
  return String(e?.message ?? e ?? 'неизвестно');
}
