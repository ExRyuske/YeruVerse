// Звуковой тракт приложения — один на всё.
//
// Здесь и только здесь заводится AudioContext, выбирается устройство вывода,
// меряются уровни и поднимается громкость выше ста процентов. На этом же
// контексте стоит шумодав микрофона: граф у приложения один.
//
// Контекстов было два — общий и отдельный у шумодава, на 48 кГц. Второй
// пересоздавался на каждую смену настройки микрофона, а движок отвечает на
// такое перенастройкой системного звука: щелчок, а то и провал в трансляции и
// в голосах собеседников, то есть ровно в том, к чему микрофон отношения не
// имеет. Поэтому контекст один и просят его сразу на 48 кГц: это частота, на
// которой работают модели шумодава, а всему остальному она безразлична.
//
// Играет звук при этом обычный <audio>/<video>, а WebAudio подключается только
// чтобы поднять громкость выше ста процентов — у элемента она упирается в
// единицу. Раньше всё шло через WebAudio, и на движке WebKit (Safari и окно
// приложения на macOS — это он) собеседников не было слышно вовсе: поток из
// WebRTC там доходит до графа обработки не всегда, а до элемента доходит всегда.

/** Частота, на которой работают модели шумодава. Другой они не умеют. */
export const MODEL_RATE = 48000;

/** Потолок усиления: дальше не громче, а грязнее. */
const MAX_GAIN = 5;

let shared = null;

/**
 * Единственный контекст приложения. Создаётся лениво — до жеста пользователя он
 * родился бы приостановленным, и уровни всегда были бы нулевыми.
 */
export function context() {
  if (!shared) {
    const Ctor = window.AudioContext || window.webkitAudioContext;
    try {
      shared = new Ctor({ sampleRate: MODEL_RATE });
    } catch {
      // Древний WebKit частоту выбирать не даёт. Всему, кроме шумодава, это
      // безразлично, а шумодав частоту проверит сам и уйдёт на подавление
      // средствами движка — о чём человеку и скажут.
      shared = new Ctor();
    }
  }
  wake();
  return shared;
}

/**
 * Разбудить тракт, если он уснул.
 *
 * Уснувший контекст не падает и не жалуется — он просто перестаёт отдавать
 * звук: дорожки живы, уровни нулевые, собеседники слышат тишину. Свернули
 * приложение на телефоне, система забрала звук под звонок — и сам он не
 * возвращается. Контекста может ещё и не быть: до первого звука поднимать его
 * незачем.
 */
function wake() {
  if (shared?.state === 'suspended') shared.resume().catch(() => {});
}

/** Работает ли тракт прямо сейчас. Обращение к нему заодно и будит. */
export function running() {
  return context().state === 'running';
}

/**
 * То же, но с ожиданием: нужно тем, кто следом строит на нём граф.
 *
 * Ждём с оглядкой на часы, и это не перестраховка. На движке WebKit (Safari и
 * окно приложения на macOS) `resume()` вне жеста пользователя не разрешается и
 * не отклоняется — промис просто не завершается никогда. Всё, что его ждало,
 * вставало молча и навсегда: ни ошибки, ни сообщения, ни признака, что
 * что-то пошло не так. Проверено в настоящем WKWebView.
 *
 * Поэтому здесь гонка с таймером, а наружу уходит честное «не поднялся» —
 * с ним зовущий хотя бы может сказать об этом человеку.
 */
export async function resume(wait = 3000) {
  const ctx = context();
  if (ctx.state !== 'running') {
    await Promise.race([
      ctx.resume().catch(() => {}),
      new Promise((r) => setTimeout(r, wait)),
    ]);
  }
  return ctx.state === 'running';
}

/** Устройство вывода умеют выбирать либо контекст, либо сами элементы. */
const ctxSink = () => typeof AudioContext !== 'undefined' && 'setSinkId' in AudioContext.prototype;
const elSink = () =>
  typeof HTMLMediaElement !== 'undefined' && 'setSinkId' in HTMLMediaElement.prototype;

export function canChooseOutput() {
  return ctxSink() || elSink();
}

/** Всё, что сейчас звучит: элемент -> чем его перезапустить, если он встанет. */
const players = new Map();
let sink = '';

/**
 * Звук, которому не дали начаться.
 *
 * Голос собеседника приходит сам, без всякого нажатия, а движки такое запускать
 * не дают: вебвью Android запрещает это прямой настройкой, Safari — политикой
 * автозапуска. Раньше всё шло через WebAudio, которому хватало одного касания за
 * всё время, а элемент требует разрешения на каждый запуск. Поэтому неудачу
 * запоминаем и повторяем при первом же касании страницы.
 */
const blocked = new Set();

/** Повторить то, что не запустилось. Функция сама решает, что ей нужно. */
export function retryOnGesture(fn) {
  blocked.add(fn);
}

/** Ждать больше нечего: элемент убрали, и запускать его при касании незачем. */
export function forgetGesture(fn) {
  blocked.delete(fn);
}

function unlock() {
  wake();
  for (const fn of [...blocked]) {
    Promise.resolve()
      .then(fn)
      .then(() => blocked.delete(fn))
      .catch(() => {});
  }
}
for (const event of ['pointerdown', 'keydown', 'touchend']) {
  document.addEventListener(event, unlock, { capture: true, passive: true });
}

// Вернулись из фона: касания может и не быть — окно просто снова на экране, а
// звук после сна телефона надо поднимать самим.
document.addEventListener('visibilitychange', () => document.hidden || wake());

/** Куда выводить звук — сразу всему приложению. */
export async function setOutput(deviceId) {
  sink = deviceId || '';
  // Ради системного устройства по умолчанию контекст не поднимаем: он родился
  // бы раньше первого звука и раньше первого касания, то есть уснувшим.
  if (ctxSink() && (sink || shared)) {
    try { await context().setSinkId(sink); } catch {}
  }
  for (const el of players.keys()) applySink(el);
}

function applySink(el) {
  if (elSink()) el.setSinkId(sink).catch(() => {});
}

/**
 * Набор устройств изменился — поднимаем звук заново.
 *
 * Случается это не только когда наушники воткнули. На Windows достаточно
 * открыть «Параметры звука»: система перебирает устройства, движок видит смену
 * того, что назначено по умолчанию, и пересоздаёт выход. Тракт при этом
 * остаётся живым, а вот элементы с чужими голосами уходят в паузу — и сами из
 * неё не возвращаются: `retryOnGesture` ждёт касания только после неудачного
 * первого запуска, а здесь первый запуск давно удался. Снаружи это выглядит
 * так: заглянул в настройки звука и перестал слышать всех до конца разговора.
 * Замечено на Windows 10.
 *
 * Поэтому будим тракт, заново назначаем выбранный выход — его устройство могло
 * исчезнуть вместе со сменой, и тогда движок вернётся к системному, — и
 * до-запускаем всё, что встало. Отказ в запуске означает, что движок ждёт
 * касания: откладываем до него тем же путём, что и первый запуск.
 */
function revive() {
  wake();
  setOutput(sink).catch(() => {});
  for (const [el, restart] of players) {
    if (!el.paused) continue;
    restart().catch(() => retryOnGesture(restart));
  }
}

navigator.mediaDevices?.addEventListener?.('devicechange', revive);

/**
 * Замер уровня на узле графа.
 *
 * Одна реализация на всё: и индикатор «сейчас говорит», и присмотр за шумодавом
 * считают громкость одинаково — по среднеквадратичному значению последнего
 * кадра. Разными они были только по недосмотру.
 */
export function tap(node) {
  const analyser = context().createAnalyser();
  analyser.fftSize = 512;
  node.connect(analyser);
  const buf = new Float32Array(analyser.fftSize);
  return {
    level() {
      analyser.getFloatTimeDomainData(buf);
      let sum = 0;
      for (const v of buf) sum += v * v;
      return Math.sqrt(sum / buf.length);
    },
    close() {
      // Отцепляем только свой замер: узел, к которому мы подключились, живёт
      // своей жизнью и может кормить ещё кого-то.
      try { node.disconnect(analyser); analyser.disconnect(); } catch {}
    },
  };
}

/**
 * Автоматический gate: пропускает поток, только пока сам решает, что в нём
 * есть звук. Порог не приходит снаружи и не завязан ни на что чужое —
 * например, на порог индикатора «говорит» (`voice.js`): тот подобран под
 * свою задачу — красиво мигать на речи, — и меняется отдельно от этого узла,
 * своей собственной настройкой.
 *
 * Принимает или готовый поток, или уже существующий узел графа. Второе — не
 * прихоть: `voice.js` без шумодава подаёт сюда узел от собственного замера
 * уровня микрофона, а не сырой `MediaStream` заново. Два `createMediaStreamSource`
 * на одном и том же локальном потоке — ровно то, что уже подводило в этом
 * проекте: на движке WebKit второй узел получал тишину, хотя первый исправно
 * слышал звук (та же беда, что с потоками из WebRTC — см. шапку файла и
 * `denoise.js`). Раздельный узел гейт закрывает сам, общий — не трогает: им
 * может пользоваться кто-то ещё.
 *
 * Порог не фиксирован, а откалиброван по месту: узел сам меряет, какой фон
 * стоит рядом, и держит порог с отступом от него, а не от одной на всех
 * цифры. С шумодавом на входе, где тишина в паузах настоящая, порог
 * опустится к самой её границе (тот же ориентир, что `SILENT_OUT` в
 * `denoise.js`); без шумодава, где «тишина» — это шум комнаты и самого
 * микрофона, порог поднимется вслед за ним — иначе гейт вообще не закрылся
 * бы ни разу, а калибровать было бы нечем.
 *
 * Калибруется всё время, а не только пока сам закрыт, — иначе как раз и
 * получался тупик без шумодава: калибровка ждала закрытия, а закрыться от
 * постоянного шума комнаты было нечем, раз порог для этого ещё не поднялся.
 *
 * Раз в `CALIBRATE_MS` порог пересчитывается на самый тихий замер за это
 * время — не плавным следованием за уровнем (то и заводило в тупик: с
 * достаточно медленным откликом порог не успевал бы подняться до шума
 * комнаты за время короткой проверки, и гейт выглядел бы попросту сломанным),
 * а честным минимумом окна. Пауза внутри фразы — обычное дело чаще, чем раз в
 * секунду, и почти любое окно её застанет; окно без единой паузы просто
 * возьмёт самое тихое место громкого куска, а следующее — поправит.
 *
 * Открытие быстрое (несколько замеров), закрытие — с запасом, чтобы не резать
 * паузы между словами; и то, и другое плавное по громкости — резкая правка
 * `gain.value` даёт слышимый щелчок. Начинает открытым: решение придёт только
 * с первым замером, и пока его нет, лучше пропустить звук, чем гарантированно
 * откусить первое слово.
 *
 * Было два готовых пути обойтись без своего порога, и оба закрылись. RNNoise
 * на самом деле считает вероятность речи внутри себя — штатный возврат
 * `rnnoise_process_frame` в оригинальной библиотеке, — но ворклет из
 * `@sapphi-red/web-noise-suppressor`, который мы вендорим, получает это число
 * и просто выбрасывает, наружу не отдаёт; достать его можно было бы только
 * правкой самого вендоренного файла, а он у нас держится чистой копией чужого
 * пакета, а не форком. Тот же пакет несёт готовый `NoiseGateWorkletNode` с
 * гистерезисом на входе/выходе — но его собственный ворклет-процессор в
 * вендоренном `workletProcessor.js` не зарегистрирован вовсе (мы вендорили
 * только модуль RNNoise), так что сам класс сейчас нерабочий пустой фасад.
 */
export function gate(input) {
  const ctx = context();
  // Свой узел заводим только если пришёл сырой поток; готовый узел — чужой,
  // и разбирать его при закрытии нельзя, см. `close()` ниже.
  const owned = input instanceof MediaStream;
  const src = owned ? ctx.createMediaStreamSource(input) : input;
  const probe = tap(src);
  const g = ctx.createGain();
  g.gain.value = 1;
  const dest = ctx.createMediaStreamDestination();
  src.connect(g).connect(dest);

  // Ниже этой отметки калибровать не на чем — там уже не фон, а цифровая
  // тишина самого тракта. Заодно и потолок чувствительности: без него
  // случайно застрявшая на нуле оценка держала бы порог неразличимым от шума
  // собственных проводов.
  const FLOOR_MIN = 0.0006;
  // Порог открытия — фон с запасом на всплеск; порог закрытия — фон с
  // запасом поменьше, чтобы гистерезис не съедал всю чувствительность у
  // тихого голоса в тихой комнате.
  const OPEN_MARGIN = 3;
  const CLOSE_MARGIN = 1.6;
  const OPEN_TICKS = 3;    // ~90 мс уверенного звука, чтобы открыться
  const CLOSE_TICKS = 25;  // ~750 мс тишины, чтобы закрыться
  const CALIBRATE_MS = 800;   // как часто пересчитывается фон

  let floor = FLOOR_MIN;
  let windowMin = Infinity;
  let windowStart = Date.now();
  let open = true;
  let above = 0;
  let below = 0;

  const timer = setInterval(() => {
    const level = probe.level();
    const openLevel = floor * OPEN_MARGIN;
    const closeLevel = Math.max(FLOOR_MIN, floor * CLOSE_MARGIN);

    if (level > openLevel) { above++; below = 0; }
    else if (level < closeLevel) { below++; above = 0; }
    else { above = 0; below = 0; }   // между порогами — держим как было

    if (!open && above >= OPEN_TICKS) open = true;
    else if (open && below >= CLOSE_TICKS) open = false;

    // Минимум за окно — фон следующего окна. Считаем всё время, а не только
    // пока закрыт: тот же тупик без шумодава, что и раньше, — калибровка
    // ждала закрытия, закрыться было не от чего, раз порог для этого ещё не
    // поднялся, — вернулся бы и на постоянном пересчёте, реши он ждать своего
    // «подходящего» момента.
    if (level < windowMin) windowMin = level;
    const now = Date.now();
    if (now - windowStart >= CALIBRATE_MS) {
      floor = Math.max(FLOOR_MIN, windowMin);
      windowMin = Infinity;
      windowStart = now;
    }

    g.gain.setTargetAtTime(open ? 1 : 0, ctx.currentTime, 0.01);
  }, 30);

  return {
    stream: dest.stream,
    close() {
      clearInterval(timer);
      const step = (fn) => { try { fn(); } catch {} };
      step(() => probe.close());
      // Свой узел разбираем целиком; чужой — только свою связь с ним, у него
      // могут быть и другие потребители (тот же общий замер уровня).
      if (owned) step(() => src.disconnect());
      else step(() => src.disconnect(g));
      step(() => g.disconnect());
      step(() => dest.stream.getTracks().forEach((t) => t.stop()));
      step(() => dest.disconnect());
    },
  };
}

/**
 * Замер громкости потока — тот же замер, только источник свой.
 *
 * `node` отдаём наружу не для красоты: если кому-то ещё нужно послушать тот
 * же локальный поток дальше по графу — см. `gate()` — правильно сделать это
 * с того же узла, а не завести на тот же поток второй `createMediaStreamSource`.
 * У локальных потоков это не всегда безопасно: второй узел на движке WebKit
 * получал тишину, хотя первый исправно слышал звук — тот же класс беды, что
 * уже ловили на потоках из WebRTC (см. шапку файла и `denoise.js`).
 */
export function meter(stream) {
  try {
    const src = context().createMediaStreamSource(stream);
    const probe = tap(src);
    return {
      level: () => probe.level(),
      node: src,
      close() {
        probe.close();
        try { src.disconnect(); } catch {}
      },
    };
  } catch {
    return null;   // в потоке нет звуковой дорожки — мерить нечего
  }
}

/**
 * Громкость media-элемента, играющего этот поток.
 *
 * До ста процентов играет сам элемент — это работает в любом движке. Выше
 * подключается усилитель WebAudio, и тогда элемент глушится, чтобы звук не шёл
 * двумя путями сразу.
 *
 * Глушится не раньше, чем усилитель докажет, что до него вообще доходит звук.
 * На движке WebKit (Safari и окно приложения на macOS) поток из WebRTC до графа
 * обработки доходит не всегда, и безусловное глушение означало ровно то, чего
 * человек не ждёт: поставил собеседнику погромче — и перестал его слышать.
 * Теперь в этом случае громкость просто упирается в сто процентов.
 */
export function volume(el, stream) {
  // Одно и то же замыкание на все перезапуски: отложенные до касания лежат
  // множеством, и новое замыкание на каждой неудаче копилось бы в нём без конца.
  const restart = () => el.play();
  players.set(el, restart);
  applySink(el);

  let boost = null;
  let level = 1;
  // Немой режим: движок не пустил звук без касания, и элемент играет молча.
  // Флаг нужен именно здесь. Пока его не было, глушение жило прямо в свойстве
  // элемента, а следующая же установка громкости — а она приходит на каждой
  // перерисовке сцены — снимала его без всякого касания. Движок на это отвечает
  // остановкой воспроизведения, и трансляция начинала дёргаться и молчать.
  let silenced = false;

  // Кто играет: усилитель (тогда элемент молчит) или сам элемент.
  const route = () => {
    const loud = level > 1 && !!boost?.alive();
    el.muted = silenced || loud;
    el.volume = loud ? 1 : Math.min(1, level);
    boost?.set(loud && !silenced ? level : 0);
  };

  return {
    set(v) {
      level = Math.min(MAX_GAIN, Math.max(0, v));
      if (level > 1 && !boost) boost = amplify(stream, route);
      route();
    },
    /** Играть молча (или перестать) — решение автозапуска, а не громкости. */
    mute(on) {
      silenced = !!on;
      route();
    },
    close() {
      players.delete(el);
      // Элемента больше нет — ждать ради него касания незачем.
      forgetGesture(restart);
      boost?.close();
      boost = null;
    },
  };
}

/** Чужой голос: свой невидимый элемент и та же громкость поверх него. */
export function playback(stream) {
  const el = new Audio();
  el.srcObject = stream;
  el.autoplay = true;
  el.style.display = 'none';   // Safari не играет элемент вне документа
  document.body.appendChild(el);
  const level = volume(el, stream);

  const play = () => el.play();
  return {
    play: () =>
      play().catch((e) => {
        retryOnGesture(play);
        throw e;                       // наверх уходит «звук заблокирован»
      }),
    set: (v) => level.set(v),
    close() {
      forgetGesture(play);
      level.close();
      el.srcObject = null;
      el.remove();
    },
  };
}

/**
 * Усилитель поверх потока: `gain` можно поднимать выше единицы.
 *
 * Media-элемент при этом всё равно нужен — без привязки потока к нему Chrome не
 * отдаёт звук в WebAudio вовсе, поэтому усилитель и живёт только рядом с
 * элементом.
 *
 * Рядом с усилением висит замер на самом источнике: по нему видно, дошёл ли
 * поток до графа. Пока в нём одни нули, усилитель молчит и звук идёт через
 * элемент; как только появится хоть что-то — зовём `onAlive`, и вызывающий
 * передаёт звук сюда. Замер стоит до регулятора: после него при нулевом
 * усилении было бы тихо всегда, и вопрос «дошёл ли поток» остался бы без
 * ответа навсегда.
 */
function amplify(stream, onAlive) {
  const ctx = context();
  let src;
  try {
    src = ctx.createMediaStreamSource(stream);
  } catch {
    // В потоке ещё нет звуковой дорожки — движки на это отвечают отказом.
    // Усиливать нечего, но дорожка может доехать позже: попробуем в другой раз.
    return null;
  }
  const gain = ctx.createGain();
  gain.gain.value = 0;

  // Лимитер после усиления, а не вместо него: выше ста процентов пики легко
  // вылезают за единицу, и без него это был бы не громкий звук, а треск от
  // цифрового клиппинга. Ratio и колено взяты жёсткими нарочно — это подпорка
  // на самый пик, а не компрессия всей речи.
  const limiter = ctx.createDynamicsCompressor();
  limiter.threshold.value = -3;
  limiter.knee.value = 0;
  limiter.ratio.value = 20;
  limiter.attack.value = 0.003;
  limiter.release.value = 0.1;
  src.connect(gain).connect(limiter).connect(ctx.destination);

  const probe = tap(src);
  let alive = false;
  const timer = setInterval(() => {
    if (probe.level() === 0) return;   // цифровая тишина — ещё не ответ
    alive = true;
    clearInterval(timer);
    onAlive();
  }, 250);

  return {
    alive: () => alive,
    set(level) {
      const v = Math.min(MAX_GAIN, Math.max(0, level));
      // Плавно: резкая правка `gain.value` щёлкает, а ползунок громкости шлёт
      // событие на каждый пиксель — то есть щёлкала бы на каждом движении.
      gain.gain.setTargetAtTime(v, ctx.currentTime, 0.015);
    },
    close() {
      clearInterval(timer);
      probe.close();
      try { src.disconnect(); gain.disconnect(); limiter.disconnect(); } catch {}
    },
  };
}
