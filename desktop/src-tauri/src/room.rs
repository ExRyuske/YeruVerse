//! «Мы в комнате» — единственное, что оболочке на Android нужно знать о
//! странице, и единственное, чего она не может выяснить сама.
//!
//! Зачем это вообще. Свёрнутому приложению Android глушит микрофон, а процесс
//! вправе выгрузить совсем — человек открыл мессенджер посмотреть, кто ему
//! написал, вернулся, а комнаты нет. Единственный законный способ этого
//! избежать — служба переднего плана с постоянным уведомлением. Но поднимать её
//! на всё время работы приложения нельзя (уведомление «идёт разговор», когда
//! никакого разговора нет), а решить, идёт ли разговор, может только сама
//! страница.
//!
//! Раньше моста не было, и Kotlin гадал по косвенному признаку — идёт ли запись
//! с микрофона. Гадание ошибалось в обе стороны: человек, который сидит в
//! комнате и только слушает, микрофон не занимает — и его разговор обрывался
//! ровно так же, как раньше.
//!
//! Мост держится на публичном API Tauri: `with_webview` отдаёт `JniHandle`, а
//! тот выполняет код на потоке Android с готовыми `JNIEnv` и объектом
//! активности. Своей JavaVM мы нигде не ищем и класс по имени не разыскиваем —
//! просто зовём метод у активности, которую нам дали. Сама активность приезжает
//! из `scripts/android_patch.py`.

/// Сообщить оболочке, в комнате мы или нет.
///
/// `wideband` — просьба не давать системе переключить звук в «разговорный»
/// режим (см. `RoomService` в `scripts/android_patch.py`). Ответа нет
/// намеренно: вызов уходит на чужой поток, а страница всё равно ничего не может
/// сделать с отказом — комната от этого не перестаёт работать, просто хуже
/// переживает сворачивание.
#[tauri::command]
pub fn set_room(app: tauri::AppHandle, active: bool, wideband: bool) {
    #[cfg(target_os = "android")]
    android(&app, active, wideband);
    // На настольных системах фон и звук устроены иначе, и делать здесь нечего.
    #[cfg(not(target_os = "android"))]
    let _ = (&app, active, wideband);
}

#[cfg(target_os = "android")]
fn android(app: &tauri::AppHandle, active: bool, wideband: bool) {
    use tauri::Manager;

    // Окно всегда одно, но берём его по метке с запасным путём: метка живёт в
    // tauri.conf.json, и молча отвалиться из-за её переименования эта дорожка
    // не должна.
    let Some(window) =
        app.get_webview_window("main").or_else(|| app.webview_windows().into_values().next())
    else {
        return;
    };

    let _ = window.with_webview(move |webview| {
        webview.jni_handle().exec(move |env, activity, _webview| {
            use jni::objects::JValue;
            // Отказ проглатываем сознательно: единственный его источник — что
            // активность оказалась не нашей (сменился шаблон Tauri), и падать
            // из-за этого посреди разговора незачем. Java-исключение, если оно
            // всё же возникло, надо снять — иначе следующий вызов JNI на этом
            // потоке упрётся в него.
            if env
                .call_method(
                    activity,
                    "setRoomActive",
                    "(ZZ)V",
                    &[JValue::Bool(active as u8), JValue::Bool(wideband as u8)],
                )
                .is_err()
            {
                let _ = env.exception_clear();
            }
        });
    });
}
